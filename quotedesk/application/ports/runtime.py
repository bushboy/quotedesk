from datetime import datetime
from typing import Protocol
from uuid import UUID

from quotedesk.application.dto.audit import AuditEvent
from quotedesk.application.dto.changes import ChangeRecord
from quotedesk.application.dto.tool_outputs import ApproveResult
from quotedesk.domain.quotes.quote import Quote
from quotedesk.domain.shared.ids import QuoteId


class Clock(Protocol):
    def now(self) -> datetime: ...


class IdGenerator(Protocol):
    def next_quote_id(self) -> QuoteId: ...

    def next_fact_id(self) -> UUID: ...


class UnitOfWork(Protocol):
    def get_quote(self, tenant_id: UUID, conversation_id: UUID) -> Quote | None: ...

    def save_quote(self, tenant_id: UUID, conversation_id: UUID, quote: Quote) -> None: ...

    def save_quote_by_id(self, tenant_id: UUID, quote: Quote) -> None: ...

    def find_change(self, tenant_id: UUID, idempotency_key: str) -> ChangeRecord | None: ...

    def save_change(self, record: ChangeRecord) -> None: ...

    def record_audit(self, event: AuditEvent) -> None: ...

    def find_operator_result(self, tenant_id: UUID, idempotency_key: str) -> ApproveResult | None: ...

    def save_operator_result(self, tenant_id: UUID, idempotency_key: str, result: ApproveResult) -> None: ...

    def list_changes(self, tenant_id: UUID) -> tuple[ChangeRecord, ...]: ...

    def list_audits(self, tenant_id: UUID) -> tuple[AuditEvent, ...]: ...

    def commit(self) -> None: ...

    def rollback(self) -> None: ...
